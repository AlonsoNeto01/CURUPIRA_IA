-- 4. RPC para gerar a grade hexagonal automaticamente a partir dos polígonos IBGE
CREATE OR REPLACE FUNCTION public.gerar_grade_hexagonal_municipios(
  p_lado_metros double precision DEFAULT 6000
)
RETURNS TABLE (codigo_ibge text, municipio text, total_hexagonos integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  r RECORD;
  v_count integer;
BEGIN
  FOR r IN
    SELECT m.codigo_ibge, m.nome, m.geom
    FROM public.municipios_ibge m
    WHERE m.ativo = true AND m.geom IS NOT NULL
    ORDER BY m.nome
  LOOP
    WITH bounds_3857 AS (
      SELECT ST_Transform(r.geom, 3857) AS geom_m
    ),
    hex_raw AS (
      SELECT
        h.i,
        h.j,
        ST_Transform(ST_SetSRID(h.geom, 3857), 4326) AS hex_4326
      FROM bounds_3857 b
      CROSS JOIN LATERAL ST_HexagonGrid(p_lado_metros, b.geom_m) AS h
      WHERE ST_Intersects(ST_SetSRID(h.geom, 3857), b.geom_m)
    )
    INSERT INTO public.grade_hexagonal_municipio (
      hex_id, codigo_ibge, centro_lat, centro_lon, geom, geojson
    )
    SELECT
      r.codigo_ibge || '_' || hr.i || '_' || hr.j AS hex_id,
      r.codigo_ibge,
      ROUND(ST_Y(ST_Centroid(hr.hex_4326))::numeric, 5)::double precision,
      ROUND(ST_X(ST_Centroid(hr.hex_4326))::numeric, 5)::double precision,
      hr.hex_4326,
      ST_AsGeoJSON(hr.hex_4326, 5)::jsonb
    FROM hex_raw hr
    ON CONFLICT (hex_id) DO NOTHING;

    SELECT COUNT(*) INTO v_count
    FROM public.grade_hexagonal_municipio g
    WHERE g.codigo_ibge = r.codigo_ibge;

    codigo_ibge := r.codigo_ibge;
    municipio := r.nome;
    total_hexagonos := v_count;
    RETURN NEXT;
  END LOOP;
END;
$$;

-- 5. RPC para atualizar a climatologia mensal (enviada em lotes pelo Colab)
CREATE OR REPLACE FUNCTION public.atualizar_climatologia_hex(p_lote jsonb)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_atualizados integer := 0;
BEGIN
  WITH entrada AS (
    SELECT
      elem->>'hex_id' AS hex_id,
      (elem->>'focos_hist_total')::integer AS focos_hist_total,
      elem->'focos_por_mes' AS focos_por_mes,
      (elem->>'risco_base_anual')::numeric(5,4) AS risco_base_anual
    FROM jsonb_array_elements(p_lote) AS elem
  ),
  upd AS (
    UPDATE public.grade_hexagonal_municipio g
    SET
      focos_hist_total = e.focos_hist_total,
      focos_por_mes = e.focos_por_mes,
      risco_base_anual = e.risco_base_anual,
      atualizado_em = now()
    FROM entrada e
    WHERE g.hex_id = e.hex_id
    RETURNING 1
  )
  SELECT COUNT(*) INTO v_atualizados FROM upd;

  RETURN v_atualizados;
END;
$$;

REVOKE ALL ON FUNCTION public.gerar_grade_hexagonal_municipios(double precision) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.gerar_grade_hexagonal_municipios(double precision) TO service_role;

REVOKE ALL ON FUNCTION public.atualizar_climatologia_hex(jsonb) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.atualizar_climatologia_hex(jsonb) TO service_role;

